import fs from 'fs';
import path from 'path';

const translationsDir = path.join(__dirname, '../messages');
const outputFile = path.join(__dirname, '../src/types/translations.d.ts');

const generateTranslationTypes = () => {
  const files = fs.readdirSync(translationsDir);
  const translations = files.reduce((acc, file) => {
    if (file.endsWith('.json')) {
      const locale = file.replace('.json', '');
      const content = JSON.parse(fs.readFileSync(path.join(translationsDir, file), 'utf8'));
      acc[locale] = content;
    }
    return acc;
  }, {});

  const types = Object.keys(translations).map(locale => {
    const keys = Object.keys(translations[locale]);
    return `type ${locale}Translations = {
${keys.map(key => `  '${key}': string;`).join('\n')}
};`;
  }).join('\n\n');

  const fileContent = `// This file is auto-generated by scripts/generate-translation-types.js

${types}

export type Translations = {
${Object.keys(translations)
    .map(locale => `  ${locale}: ${locale}Translations;`)
    .join('\n')}
};
`;

  fs.writeFileSync(outputFile, fileContent);
};

generateTranslationTypes();
